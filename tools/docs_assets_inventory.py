#!/usr/bin/env python3
"""Regenerate the inventory table in docs/site/assets/README.md.

For every file under docs/site/assets it lists the site pages that reference it (by nav title) and the capture
script or class that produces it, so a stale, unused or hand-made image is visible at a glance (docs audit
2026-10-17 §3). Run from the repository root:

    python3 tools/docs_assets_inventory.py

It rewrites only the text between the README's two INVENTORY markers.
"""
import glob
import os
import re

ASSETS = "docs/site/assets"
README = os.path.join(ASSETS, "README.md")
BEGIN = "<!-- BEGIN INVENTORY: generated by tools/docs_assets_inventory.py -->"
END = "<!-- END INVENTORY -->"
# names built at run time rather than spelled in full in a capture script
COMPUTED = {
    r"^spotlight(-dark)?\.png$": "capture-docs.py",
    r"^spotlight-findings-(light|dark)\.png$": "capture-docs.py",
    r"^spotlight-walk(-dark)?\.png$": "capture-docs.py",
    r"^conv-.*\.png$": "capture-conversations.py",
    r"^journey.*\.png$": "capture-journey.py",
    r"^find-the-first-recorded-breach\.": "capture-journey.py",
}
NOT_PRODUCERS = re.compile(r"^(test_.*|check-.*|journey-old-reader\.py|docs_assets_inventory\.py)$")


def nav_titles():
    titles = {}
    for line in open("mkdocs.yml", encoding="utf-8"):
        m = re.match(r"\s*- (.+?): ([\w./-]+\.md)\s*$", line)
        if m:
            titles[m.group(2)] = m.group(1).strip("'")
    return titles


def page_title(page, titles):
    rel = os.path.relpath(page, "docs/site")
    if rel in titles:
        return titles[rel]
    for line in open(page, encoding="utf-8"):
        if line.startswith("# "):
            return line[2:].strip()
    return rel


def mentions(text, name):
    """True when text names the file itself, not a longer name that ends with it (spotlight.png in java-source-spotlight.png)."""
    return re.search(r"(?<![\w-])" + re.escape(name) + r"(?![\w-])", text) is not None


def rows():
    titles = nav_titles()
    pages = [p for p in sorted(glob.glob("docs/site/**/*.md", recursive=True)) if p != README]
    texts = {p: open(p, encoding="utf-8").read() for p in pages}
    tools = [t for t in sorted(glob.glob("tools/*.py") + glob.glob("tools/*.java"))
             if not NOT_PRODUCERS.match(os.path.basename(t))]
    tool_texts = {t: open(t, encoding="utf-8").read() for t in tools}
    out = []
    for asset in sorted(glob.glob(os.path.join(ASSETS, "**", "*"), recursive=True)):
        if not os.path.isfile(asset) or asset == README:
            continue
        rel = os.path.relpath(asset, ASSETS)
        name = os.path.basename(asset)
        used = sorted({page_title(p, titles) for p, t in texts.items() if mentions(t, rel) or ("/" in rel and mentions(t, name))})
        made = sorted({os.path.basename(t) for t, s in tool_texts.items() if mentions(s, name)})
        for pattern, tool in COMPUTED.items():
            if re.search(pattern, name):
                made = sorted(set(made) | {tool})
        out.append((rel, used, made))
    return out


def table():
    lines = ["| File | Used on | Produced by |", "|---|---|---|"]
    for rel, used, made in rows():
        lines.append("| `%s` | %s | %s |" % (rel, ", ".join(used) if used else "**unused**",
                                            ", ".join("`%s`" % m for m in made) if made else "no harness"))
    return "\n".join(lines)


def main():
    text = open(README, encoding="utf-8").read()
    b, e = text.index(BEGIN), text.index(END)
    text = text[:b + len(BEGIN)] + "\n\n" + table() + "\n\n" + text[e:]
    open(README, "w", encoding="utf-8").write(text)


if __name__ == "__main__":
    main()
