package telamin.fluxtion.audit.analyser.analyser.llm;

import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Docs restructure, phase 7: the argument tables at the end of {@code docs/site/reference/verbs.md} are GENERATED from
 * {@link VerbSchemas} — the same schemas {@code GET /manifest} and the MCP bridge publish — and this test fails when the
 * page and the schemas drift apart. The audit found the page's verb count wrong twice (17 vs 18) because it was
 * hand-copied; a generated section with a sync check cannot be.
 *
 * <p>To regenerate after changing a schema:
 * {@code mvn -o -q test -Dtest=VerbReferenceSyncTest -Dverbs.regenerate=true}, then review the page's diff.
 *
 * <p>Wrong-result witness: add a property to any verb's schema (or edit a description) without regenerating; the
 * assertion fails and names the regenerate command.
 */
class VerbReferenceSyncTest {

    static final Path PAGE = Path.of("docs/site/reference/verbs.md");
    static final String BEGIN = "<!-- BEGIN GENERATED by VerbReferenceSyncTest from VerbSchemas: do not edit by hand -->";
    static final String END = "<!-- END GENERATED -->";

    @Test
    void theGeneratedArgumentTablesMatchVerbSchemas() throws Exception {
        String page = Files.readString(PAGE);
        int b = page.indexOf(BEGIN);
        int e = page.indexOf(END);
        assertTrue(b >= 0 && e > b, PAGE + " must hold the generated section between its markers");
        String want = render();
        String have = page.substring(b + BEGIN.length(), e);
        if (Boolean.getBoolean("verbs.regenerate") && !have.equals(want)) {
            Files.writeString(PAGE, page.substring(0, b + BEGIN.length()) + want + page.substring(e));
            return;
        }
        assertEquals(want, have, PAGE + " has drifted from VerbSchemas — regenerate it with "
                + "`mvn -o -q test -Dtest=VerbReferenceSyncTest -Dverbs.regenerate=true` and review the diff");
    }

    @Test
    void everyPublishedVerbAndProposeHaveATable() throws Exception {
        String page = Files.readString(PAGE);
        for (String verb : VerbSchemas.hosted().keySet()) {
            assertTrue(page.contains("### `" + verb + "` arguments"), "no generated table for " + verb);
        }
    }

    /** The generated section: one heading, description and argument table per verb, in schema order, then propose. */
    @SuppressWarnings("unchecked")
    static String render() {
        StringBuilder out = new StringBuilder("\n\n");
        Map<String, Object> hosted = VerbSchemas.hosted();
        for (Map.Entry<String, Object> v : hosted.entrySet()) {
            String verb = v.getKey();
            Map<String, Object> schema = (Map<String, Object>) v.getValue();
            out.append("### `").append(verb).append("` arguments\n\n");
            if (VerbSchemas.PROPOSE.equals(verb)) {
                out.append("*Offered only to Claude Code in the analyser: never on `/manifest`, the MCP bridge or the "
                        + "in-app assistant.*\n\n");
            } else {
                out.append("MCP tool `analyser_").append(verb).append("`.\n\n");
            }
            Object desc = schema.get("description");
            if (desc != null) out.append(text(desc.toString())).append("\n\n");
            Map<String, Object> props = (Map<String, Object>) schema.get("properties");
            List<String> required = schema.get("required") instanceof List<?> r ? (List<String>) r : List.of();
            if (props == null || props.isEmpty()) {
                out.append("No arguments.\n\n");
                continue;
            }
            out.append("| Argument | Type | Required | Description |\n|---|---|---|---|\n");
            for (Map.Entry<String, Object> p : props.entrySet()) {
                Map<String, Object> spec = (Map<String, Object>) p.getValue();
                Object d = spec.get("description");
                out.append("| `").append(p.getKey()).append("` | ").append(type(spec)).append(" | ")
                        .append(required.contains(p.getKey()) ? "yes" : "").append(" | ")
                        .append(d == null ? "" : text(d.toString())).append(" |\n");
            }
            out.append('\n');
        }
        return out.toString();
    }

    /** A schema's type in a few words: a JSON type, its enum, an array's item type, an object's fields. */
    @SuppressWarnings("unchecked")
    static String type(Map<String, Object> spec) {
        if (spec.get("anyOf") instanceof List<?> any) {
            StringBuilder s = new StringBuilder();
            for (Object o : any) {
                if (!s.isEmpty()) s.append(" or ");
                s.append(type((Map<String, Object>) o));
            }
            return s.toString();
        }
        if (spec.get("enum") instanceof List<?> values) {
            StringBuilder s = new StringBuilder();
            for (Object o : values) {
                if (!s.isEmpty()) s.append(", ");
                s.append('`').append(o).append('`');
            }
            return "one of " + s;
        }
        Object t = spec.get("type");
        if ("array".equals(t) && spec.get("items") instanceof Map<?, ?> items) {
            return "array of " + type((Map<String, Object>) items);
        }
        if ("object".equals(t) && spec.get("properties") instanceof Map<?, ?> fields && !fields.isEmpty()) {
            StringBuilder s = new StringBuilder();
            for (Object k : fields.keySet()) {
                if (!s.isEmpty()) s.append(", ");
                s.append('`').append(k).append('`');
            }
            return "object (" + s + ")";
        }
        return t == null ? "any" : t.toString();
    }

    /** Schema prose as literal Markdown text: no line breaks, no table pipes, no emphasis, links or HTML. */
    static String text(String s) {
        StringBuilder out = new StringBuilder();
        for (char c : s.replace("\r", " ").replace("\n", " ").toCharArray()) {
            switch (c) {
                case '<' -> out.append("&lt;");
                case '>' -> out.append("&gt;");
                case '&' -> out.append("&amp;");
                case '|', '*', '_', '[', ']', '`', '\\' -> out.append('\\').append(c);
                default -> out.append(c);
            }
        }
        return out.toString().trim();
    }
}
